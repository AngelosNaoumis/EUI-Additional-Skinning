"""Generate docs/API.md: every ns.* and H.* function with its signature, the comment above it
and where it is, so readers (and AI tools) look things up here instead of reading the Lua.

    python scripts/api_index.py          # rewrite docs/API.md
    python scripts/api_index.py --check  # exit 1 if docs/API.md is out of date (lint runs this)
"""
import argparse
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
addon = root / 'EUIAdditionalSkinning'
OUT = root / 'docs' / 'API.md'
SOURCES = ['Core.lua', 'Skin.lua', 'Widgets.lua', 'Helpers.lua', 'Accent.lua', 'Dev.lua']
DEF = re.compile(r'^\s*function\s+((?:ns|H)\.[A-Za-z_]+)\s*\(([^)]*)\)')


def entries(path):
    lines = path.read_text().splitlines()
    for number, line in enumerate(lines, 1):
        m = DEF.match(line)
        if not m:
            continue
        comment, i = [], number - 2
        while i >= 0 and lines[i].strip().startswith('--'):
            comment.insert(0, lines[i].strip().lstrip('-').strip())
            i -= 1
        yield m.group(1), m.group(2).strip(), ' '.join(comment), f'{path.name}:{number}'


def render():
    out = ['# API reference', '',
           'Generated by `python scripts/api_index.py` from the comments above each definition; do not edit by hand.',
           'How to use these in a skin: [SKIN-DEVELOPMENT.md](../SKIN-DEVELOPMENT.md).', '']
    for source in SOURCES:
        rows = list(entries(addon / source))
        if not rows:
            continue
        out += [f'## {source}', '', '| Function | What it does | Where |', '| --- | --- | --- |']
        for name, params, comment, where in rows:
            text = comment.replace('|', '\\|') or '-'
            out.append(f'| `{name}({params})` | {text} | `{where}` |')
        out.append('')
    return '\n'.join(out)


parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
text = render()
if args.check:
    if not OUT.is_file() or OUT.read_text() != text:
        sys.exit('docs/API.md is out of date: run python scripts/api_index.py')
else:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f'Wrote {OUT.relative_to(root)}')
